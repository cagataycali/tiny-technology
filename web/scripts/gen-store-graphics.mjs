#!/usr/bin/env node
/**
 * gen-store-graphics.mjs — the marketplace graphics that aren't screenshots.
 *
 * Store listings need art the app itself can't produce: Play's 1024×500 feature
 * graphic, and the type-only social cards (Instagram can't post a raw 1080×2410
 * phone shot — 4:5 crop destroys it, see store-assets/social/instagram.md).
 *
 * Palette and mark geometry are IMPORTED from gen-logo.mjs, so a re-brand
 * (`node scripts/gen-logo.mjs "#bd93f9"`) re-colors these too — there is no
 * second copy of the brand here.
 *
 *   node scripts/gen-store-graphics.mjs            # brand green #00FF88
 *   node scripts/gen-store-graphics.mjs "#bd93f9"  # any accent
 *
 * Emits (PNGs need rsvg-convert on PATH, same dependency as gen-logo.mjs):
 *   store-assets/final/play-feature-graphic-1024x500.{svg,png}
 *   store-assets/final/play-icon-512.png          ← Play's REQUIRED hi-res icon (c48)
 *   store-assets/final/social-pricing-card-1080x1350.{svg,png}
 *   store-assets/final/social-quote-card-1080x1350.{svg,png}
 *
 * ⚠️ c48 — the hi-res icon. Play REQUIRES a 512×512 32-bit PNG per listing and there was no
 * 512² icon anywhere that a Play upload could read: `gen-logo.mjs` emits the PWA 512s, the iOS
 * 1024s and the Android adaptive-icon vector, and the Play tree held only `featureGraphic.png`.
 * The icon is rendered from `iconSvg` — the SAME source as every other icon — so it re-colors
 * with a re-brand and cannot drift from the mark. It is deliberately NOT a copy of
 * `public/icon-512.png`: that file is a PWA asset whose purpose could change independently, and
 * two files with one purpose is the drift shape this whole toolchain exists to prevent.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'
import { derivePalette, iconSvg } from './gen-logo.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'store-assets', 'final')

/** The logo mark as a reusable <g>, scaled/translated into any canvas.
 *  Static (no <animate>) — every store rasterizes, and rsvg ignores SMIL
 *  anyway, so an animated source would silently render at its rest frame. */
const mark = (p, id, cx, cy, size) => {
  const s = size / 120
  return `  <g transform="translate(${cx - size / 2} ${cy - size / 2}) scale(${s})">
    <circle cx="60" cy="60" r="34" fill="url(#${id}-glow)"/>
    <circle cx="60" cy="18" r="4" fill="${p.accent}"/>
    <circle cx="102" cy="60" r="3" fill="${p.accent}" opacity="0.8"/>
    <circle cx="60" cy="102" r="3.4" fill="${p.lightDot}"/>
    <circle cx="24" cy="44" r="2.6" fill="${p.accent}" opacity="0.7"/>
    <circle cx="96" cy="88" r="2.6" fill="${p.accent}" opacity="0.7"/>
    <circle cx="60" cy="60" r="15" fill="url(#${id}-core)"/>
  </g>`
}

const gradients = (p, id) => `  <defs>
    <radialGradient id="${id}-glow" cx="50%" cy="50%" r="50%">
      <stop offset="0%" stop-color="${p.accent}" stop-opacity="0.85"/>
      <stop offset="55%" stop-color="${p.accent}" stop-opacity="0.22"/>
      <stop offset="100%" stop-color="${p.accent}" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="${id}-core" cx="50%" cy="45%" r="55%">
      <stop offset="0%" stop-color="${p.highlight}"/>
      <stop offset="45%" stop-color="${p.accent}"/>
      <stop offset="100%" stop-color="${p.shade}"/>
    </radialGradient>
    <radialGradient id="${id}-wash" cx="50%" cy="50%" r="60%">
      <stop offset="0%" stop-color="${p.accent}" stop-opacity="0.13"/>
      <stop offset="100%" stop-color="${p.accent}" stop-opacity="0"/>
    </radialGradient>
  </defs>`

// System font stack: rsvg resolves these on macOS, and no webfont means no
// license question in a store asset.
const FONT = 'Helvetica Neue, Helvetica, Arial, sans-serif'

/**
 * Play feature graphic — 1024×500, REQUIRED for a store video.
 *
 * Play overlays a play button dead centre when a promo video is attached and
 * crops the edges on some surfaces, so the composition is deliberately
 * off-centre: mark + wordmark left, tagline under it, centre-right kept empty.
 */
export function featureGraphicSvg(p) {
  const W = 1024, H = 500
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <!-- Play feature graphic (1024×500). GENERATED by scripts/gen-store-graphics.mjs.
       Centre is left empty on purpose: Play stamps a play button there when a
       promo video is attached. Nothing important within 50px of any edge. -->
${gradients(p, 'fg')}
  <rect width="${W}" height="${H}" fill="${p.bg}"/>
  <ellipse cx="250" cy="250" rx="520" ry="420" fill="url(#fg-wash)"/>
${mark(p, 'fg', 150, 250, 190)}
  <text x="290" y="238" font-family="${FONT}" font-size="112" font-weight="700" fill="${p.accent}">tiny</text>
  <text x="294" y="300" font-family="${FONT}" font-size="34" font-weight="400" fill="#e8e8e8">create your own AI by chatting</text>
  <text x="294" y="348" font-family="${FONT}" font-size="26" font-weight="400" fill="#8a8a8a">it remembers · it speaks · it runs on every device you own</text>
</svg>
`
}

/** Instagram 4:5 card, type-only — the cheapest postable asset (no screenshot,
 *  so it needs no privacy scrub). Lines are passed in so the same geometry
 *  serves the pricing card and the quote card. */
export function socialCardSvg(p, id, { kicker, lines, footer }) {
  const W = 1080, H = 1350
  // Vertical rhythm: block centred on the canvas, never inside the outer 8%
  // (IG's UI overlays avatars/actions at the extremes).
  // Leading is PROPORTIONAL to each line's size (1.4×), not a fixed step — a
  // constant lineH stranded the 58px lines with the same gap as the 96px ones,
  // which reads as two unrelated blocks instead of one paragraph.
  const lead = (l) => (l.size || 84) * 1.4
  const offsets = []
  let acc = 0
  for (const l of lines) {
    offsets.push(acc)
    acc += lead(l)
  }
  const blockH = acc - lead(lines[lines.length - 1])
  // Centre the block in the space BETWEEN the kicker (y=400) and the footer
  // (y=1215) rather than on the raw canvas centre — the mark + kicker occupy
  // the top third, so canvas-centring left a visible dead gap above the footer.
  const startY = (400 + 1215) / 2 - blockH / 2 + 30
  const body = lines
    .map((l, i) => {
      const y = startY + offsets[i]
      const fill = l.accent ? p.accent : '#f2f2f2'
      const weight = l.accent ? 700 : 600
      return `  <text x="${W / 2}" y="${y}" text-anchor="middle" font-family="${FONT}" font-size="${l.size || 84}" font-weight="${weight}" fill="${fill}">${l.t}</text>`
    })
    .join('\n')
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <!-- Instagram 4:5 card. GENERATED by scripts/gen-store-graphics.mjs.
       Type-only by design: raw phone screenshots are 1080×2410 and IG's 4:5
       crop destroys them (store-assets/social/instagram.md). -->
${gradients(p, id)}
  <rect width="${W}" height="${H}" fill="${p.bg}"/>
  <ellipse cx="540" cy="700" rx="620" ry="700" fill="url(#${id}-wash)"/>
${mark(p, id, 540, 250, 150)}
  <text x="${W / 2}" y="400" text-anchor="middle" font-family="${FONT}" font-size="34" font-weight="500" fill="${p.accent}" letter-spacing="6">${kicker}</text>
${body}
  <text x="${W / 2}" y="1215" text-anchor="middle" font-family="${FONT}" font-size="36" font-weight="400" fill="#9a9a9a">${footer}</text>
  <text x="${W / 2}" y="1272" text-anchor="middle" font-family="${FONT}" font-size="32" font-weight="600" fill="${p.accent}">tiny.technology</text>
</svg>
`
}

const PRICING_CARD = {
  kicker: 'THE WHOLE FEE',
  lines: [
    { t: 'Price it at $0.50', size: 76 },
    { t: 'you keep $0.499', size: 92, accent: true },
    { t: 'Price it at $5.00', size: 76 },
    { t: 'you keep $4.999', size: 92, accent: true },
  ],
  footer: 'a flat $0.001 per paid call — not a percentage',
}

const QUOTE_CARD = {
  kicker: 'WHAT A TINY IS',
  lines: [
    { t: 'An AI you make', size: 96 },
    { t: 'by talking to it.', size: 96, accent: true },
    { t: 'It remembers what you', size: 58 },
    { t: 'teach it. Permanently.', size: 58 },
  ],
  footer: 'free to create · free to keep',
}

const png = (svgText, outPng, width) => {
  const tmp = mkdtempSync(join(tmpdir(), 'tiny-store-'))
  try {
    const svgPath = join(tmp, 'in.svg')
    writeFileSync(svgPath, svgText)
    execFileSync('rsvg-convert', ['-w', String(width), '-o', outPng, svgPath])
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}

const main = () => {
  const accent = process.argv[2] || '#00FF88'
  const p = derivePalette(accent)
  mkdirSync(OUT, { recursive: true })

  const jobs = [
    ['play-feature-graphic-1024x500', featureGraphicSvg(p), 1024],
    ['social-pricing-card-1080x1350', socialCardSvg(p, 'pc', PRICING_CARD), 1080],
    ['social-quote-card-1080x1350', socialCardSvg(p, 'qc', QUOTE_CARD), 1080],
  ]
  for (const [name, svg, w] of jobs) {
    const svgPath = join(OUT, `${name}.svg`)
    writeFileSync(svgPath, svg)
    png(svg, join(OUT, `${name}.png`), w)
    console.log(`✓ ${name}.svg + .png`)
  }

  // Play's required hi-res icon. PNG only — no `.svg` sibling, because the source of truth for
  // this artwork is `public/icon-source.svg` (written by gen-logo.mjs from the same `iconSvg`).
  // Emitting a second SVG here would be exactly the two-copies-of-one-truth shape the rest of
  // this toolchain is built to avoid; the PNG is a rasterization, not a source.
  //
  // ⚠️ Play rejects an icon with an alpha channel in some flows and the 32-bit PNG it asks for is
  // opaque RGBA; `iconSvg` paints a full-bleed opaque background rect for exactly this reason
  // (it is the "static, opaque square" variant, unlike the rounded `logo.svg`). Pinned by
  // tests/store-icon-conformance.test.ts — do NOT swap the source for `animatedSvg`, whose
  // rounded corners would leave transparent pixels at every corner.
  png(iconSvg(p), join(OUT, 'play-icon-512.png'), 512)
  console.log('✓ play-icon-512.png (Play hi-res icon, from iconSvg)')

  console.log(`\naccent ${accent} → ${OUT}`)
}

if (import.meta.url === `file://${process.argv[1]}`) main()
